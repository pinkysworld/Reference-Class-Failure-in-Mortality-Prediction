#!/usr/bin/env python3
"""
Reference-class failure in mortality prediction: synthetic experiment.

Two patient regimes share overlapping observable features but are generated by
different conditional outcome mechanisms (concept shift) governed by an
unmeasured latent terminal state. Supervised models are trained only on the
reference regime and evaluated in both regimes. The script reproduces every
figure, table, and numeric anchor reported in the manuscript, plus a sensitivity
analysis separating concept shift from covariate shift and from base-rate shift.

Usage
-----
    python run_reference_class_experiment.py --seeds 20

Outputs are written to ./outputs, ./figures, and ./tables.
"""
import argparse
import json
import os
import sys
import time
import warnings

import numpy as np
import pandas as pd
from numpy.random import default_rng
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, HistGradientBoostingClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import roc_auc_score, brier_score_loss
from sklearn.covariance import EmpiricalCovariance

warnings.filterwarnings("ignore")

# ---------------------------------------------------------------------------
# Data-generating process (fixed; see Table S1)
# ---------------------------------------------------------------------------
FEATURES = ["age", "comorbidity_burden", "organ_dysfunction_score",
            "treatment_intensity", "inflammatory_burden", "frailty"]
P = len(FEATURES)

MU_REF = np.zeros(P)
BETA_REF = np.array([0.70, 0.60, 0.95, -0.50, 0.55, 0.85])
B0_REF = -0.95                       # reference prevalence ~ 0.35

MU_NOV = np.array([0.30, 0.25, 0.45, 0.40, 0.30, 0.55])
BETA_NOV = np.array([0.20, 0.55, 1.70, 1.25, 0.95, 1.55])
B0_NOV = -0.20                       # novel terminal prevalence ~ 0.76

SIZES = [250, 500, 1000, 2000, 4000, 8000]
N_TEST = 6000


def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def gen(n, mu, beta, b0, rng):
    X = rng.normal(size=(n, P)) + mu
    p = sigmoid(b0 + X @ beta)
    y = (rng.uniform(size=n) < p).astype(int)
    return X, y, p


def gen_regime(n, regime, rng):
    if regime == "reference":
        return gen(n, MU_REF, BETA_REF, B0_REF, rng)
    return gen(n, MU_NOV, BETA_NOV, B0_NOV, rng)


# ---------------------------------------------------------------------------
# Metrics
# ---------------------------------------------------------------------------
def calibration_slope(y, p):
    p = np.clip(p, 1e-6, 1 - 1e-6)
    logit = np.log(p / (1 - p)).reshape(-1, 1)
    try:
        lr = LogisticRegression(C=1e6, max_iter=1000).fit(logit, y)
        return float(lr.coef_[0, 0])
    except Exception:
        return np.nan


def ece(y, p, bins=10):
    edges = np.linspace(0, 1, bins + 1)
    idx = np.digitize(p, edges[1:-1])
    out = 0.0
    for b in range(bins):
        m = idx == b
        if m.sum():
            out += m.mean() * abs(y[m].mean() - p[m].mean())
    return float(out)


def high_confidence_error(y, p, thr=0.9):
    conf = np.maximum(p, 1 - p)
    m = conf >= thr
    if m.sum() == 0:
        return np.nan
    return float(np.mean((p[m] >= 0.5).astype(int) != y[m]))


def metrics(y, p):
    return dict(
        auroc=float(roc_auc_score(y, p)) if len(np.unique(y)) > 1 else np.nan,
        brier=float(brier_score_loss(y, p)),
        ece=ece(y, p),
        calibration_slope=calibration_slope(y, p),
        sharpness=float(np.mean(np.maximum(p, 1 - p))),
        high_confidence_error=high_confidence_error(y, p),
        mean_prediction=float(np.mean(p)),
    )


def models():
    return {
        "Logistic regression": LogisticRegression(max_iter=2000),
        "Random forest": RandomForestClassifier(
            n_estimators=200, min_samples_leaf=5, n_jobs=-1, random_state=0),
        "Gradient boosting": HistGradientBoostingClassifier(
            max_depth=3, learning_rate=0.06, max_iter=300, random_state=0),
        "Neural network": MLPClassifier(
            hidden_layer_sizes=(64, 32), alpha=1e-3, max_iter=400,
            early_stopping=True, random_state=0),
    }


# ---------------------------------------------------------------------------
# Experiment
# ---------------------------------------------------------------------------
def _reps(seeds):
    return range(seeds) if isinstance(seeds, int) else list(seeds)


def run_sweep(seeds):
    rows = []
    for rep in _reps(seeds):
        rng = default_rng(1000 + rep)
        Xr, yr, _ = gen_regime(N_TEST, "reference", rng)
        Xn, yn, _ = gen_regime(N_TEST, "novel", rng)
        Xf, yf, _ = gen_regime(max(SIZES), "reference", rng)
        for n in SIZES:
            Xt, yt = Xf[:n], yf[:n]
            for name, mdl in models().items():
                mdl.fit(Xt, yt)
                for regime, (Xte, yte) in (("reference", (Xr, yr)),
                                           ("novel", (Xn, yn))):
                    m = metrics(yte, mdl.predict_proba(Xte)[:, 1])
                    m.update(model=name, training_n=n, regime=regime, seed=rep)
                    rows.append(m)
    return pd.DataFrame(rows)


def selective_and_novelty(seeds):
    sel, nov = [], []
    for rep in _reps(seeds):
        rng = default_rng(1000 + rep)
        Xr, yr, _ = gen_regime(N_TEST, "reference", rng)
        Xn, yn, _ = gen_regime(N_TEST, "novel", rng)
        Xf, yf, _ = gen_regime(max(SIZES), "reference", rng)
        gb = HistGradientBoostingClassifier(
            max_depth=3, learning_rate=0.06, max_iter=300, random_state=0).fit(Xf, yf)
        for regime, (Xte, yte) in (("reference", (Xr, yr)), ("novel", (Xn, yn))):
            p = gb.predict_proba(Xte)[:, 1]
            conf = np.maximum(p, 1 - p)
            for cov in [1.0, 0.9, 0.8, 0.7, 0.6, 0.5]:
                thr = np.quantile(conf, 1 - cov)
                keep = conf >= thr
                sel.append(dict(seed=rep, regime=regime, coverage=cov,
                                brier_retained=float(brier_score_loss(yte[keep], p[keep])),
                                retained_n=int(keep.sum())))
        cov_est = EmpiricalCovariance().fit(Xf)
        scores = np.r_[cov_est.mahalanobis(Xr), cov_est.mahalanobis(Xn)]
        labels = np.r_[np.zeros(N_TEST), np.ones(N_TEST)]
        nov.append(dict(seed=rep, novelty_auroc=float(roc_auc_score(labels, scores))))
    return pd.DataFrame(sel), pd.DataFrame(nov)


def anchors(seeds):
    rng = default_rng(7)
    _, yr, pr = gen_regime(60000, "reference", rng)
    _, yn, pn = gen_regime(60000, "novel", rng)
    bayes_ref = float(np.mean(pr * (1 - pr)))
    bayes_nov = float(np.mean(pn * (1 - pn)))
    Xon, yon, _ = gen_regime(8000, "novel", default_rng(11))
    oracle = HistGradientBoostingClassifier(max_depth=3, max_iter=300,
                                            random_state=0).fit(Xon, yon)
    Xnh, ynh, _ = gen_regime(N_TEST, "novel", default_rng(12))
    oracle_nov = float(brier_score_loss(ynh, oracle.predict_proba(Xnh)[:, 1]))
    return dict(bayes_brier_reference=bayes_ref, bayes_brier_novel=bayes_nov,
                oracle_brier_novel=oracle_nov,
                reference_prevalence=float(yr.mean()),
                novel_prevalence=float(yn.mean()))


def sensitivity(seeds):
    # match novel prevalence to the reference (~0.35) by solving for the intercept
    rng0 = default_rng(0)
    Xc = rng0.normal(size=(200000, P)) + MU_NOV
    lin = Xc @ BETA_NOV
    lo, hi = -12.0, 12.0
    for _ in range(60):                       # bisection for prevalence target
        mid = 0.5 * (lo + hi)
        if sigmoid(mid + lin).mean() - 0.35 > 0:
            hi = mid
        else:
            lo = mid
    b0_match = 0.5 * (lo + hi)
    scenarios = {
        "main": dict(mu=MU_NOV, beta=BETA_NOV, b0=B0_NOV),
        "concept_shift_only_no_feature_shift": dict(mu=MU_REF, beta=BETA_NOV, b0=B0_NOV),
        "prevalence_matched_novel": dict(mu=MU_NOV, beta=BETA_NOV, b0=b0_match),
    }
    rows = []
    for rep in _reps(seeds):
        rng = default_rng(1000 + rep)
        Xtr, ytr, _ = gen_regime(8000, "reference", rng)
        gb = HistGradientBoostingClassifier(
            max_depth=3, learning_rate=0.06, max_iter=300, random_state=0).fit(Xtr, ytr)
        for name, c in scenarios.items():
            Xte, yte, pte = gen(N_TEST, c["mu"], c["beta"], c["b0"], rng)
            pr = gb.predict_proba(Xte)[:, 1]
            rows.append(dict(scenario=name, seed=rep,
                             outcome_prevalence=float(yte.mean()),
                             bayes_brier=float(np.mean(pte * (1 - pte))),
                             model_brier=float(brier_score_loss(yte, pr)),
                             ece=ece(yte, pr),
                             auroc=float(roc_auc_score(yte, pr))))
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Figures
# ---------------------------------------------------------------------------
def make_figures(df, sel, d_ref, d_nov, ood_auroc, bayes_ref, bayes_nov, seeds, figdir):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 11, "figure.dpi": 200,
                         "axes.spines.top": False, "axes.spines.right": False})
    REF_C, NOV_C = "#2c7fb8", "#d6604d"
    MODELS = list(models().keys())

    def ms(model, regime, col):
        g = df[(df.model == model) & (df.regime == regime)].groupby("training_n")[col]
        return g.mean(), g.std()

    fig, axes = plt.subplots(2, 2, figsize=(10, 7.5), sharex=True)
    for ax, model in zip(axes.ravel(), MODELS):
        for regime, c in [("reference", REF_C), ("novel", NOV_C)]:
            m, s = ms(model, regime, "brier")
            ax.plot(m.index, m.values, "-o", color=c, label=regime.capitalize())
            ax.fill_between(m.index, m - s, m + s, color=c, alpha=0.15)
        ax.axhline(bayes_ref, ls=":", color=REF_C, lw=1)
        ax.axhline(bayes_nov, ls=":", color=NOV_C, lw=1)
        ax.set_xscale("log"); ax.set_title(model)
        ax.set_xlabel("Training sample size (log)"); ax.set_ylabel("Brier score")
    axes[0, 0].legend(frameon=False, title="Test regime", fontsize=9)
    fig.suptitle("Reducible vs. irreducible error: Brier under increasing reference data", y=0.995)
    fig.tight_layout(); fig.savefig(f"{figdir}/figure1_brier_by_training_size.png", bbox_inches="tight"); plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.6))
    for ax, (regime, c) in zip(axes, [("reference", REF_C), ("novel", NOV_C)]):
        ps, ys = [], []
        for rep in range(seeds):
            rng = default_rng(1000 + rep)
            Xr, yr, _ = gen_regime(N_TEST, "reference", rng)
            Xn, yn, _ = gen_regime(N_TEST, "novel", rng)
            Xf, yf, _ = gen_regime(max(SIZES), "reference", rng)
            g = HistGradientBoostingClassifier(max_depth=3, max_iter=300, random_state=0).fit(Xf, yf)
            if regime == "reference":
                ps.append(g.predict_proba(Xr)[:, 1]); ys.append(yr)
            else:
                ps.append(g.predict_proba(Xn)[:, 1]); ys.append(yn)
        p = np.concatenate(ps); y = np.concatenate(ys)
        edges = np.linspace(0, 1, 11); idx = np.digitize(p, edges[1:-1]); xs, obs = [], []
        for b in range(10):
            mb = idx == b
            if mb.sum() > 50:
                xs.append(p[mb].mean()); obs.append(y[mb].mean())
        ax.plot([0, 1], [0, 1], "k--", lw=1, label="Perfect calibration")
        ax.plot(xs, obs, "-o", color=c, label="Observed")
        ax.set_title(f"{regime.capitalize()} regime"); ax.set_xlim(0, 1); ax.set_ylim(0, 1)
        ax.set_xlabel("Predicted probability"); ax.set_ylabel("Observed mortality")
        ax.legend(frameon=False, loc="upper left", fontsize=9)
    fig.suptitle("Calibration: reliable in-reference, broken on the novel phenotype (gradient boosting)")
    fig.tight_layout(); fig.savefig(f"{figdir}/figure2_reliability_diagram.png", bbox_inches="tight"); plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.4))
    ax = axes[0]
    for regime, c in [("reference", REF_C), ("novel", NOV_C)]:
        m, s = ms("Gradient boosting", regime, "sharpness")
        ax.plot(m.index, m.values, "-o", color=c, label=regime.capitalize())
        ax.fill_between(m.index, m - s, m + s, color=c, alpha=0.15)
    ax.set_xscale("log"); ax.set_ylim(0.5, 1.0)
    ax.set_xlabel("Training sample size (log)"); ax.set_ylabel("Sharpness (mean confidence)")
    ax.set_title("Similarly high confidence on novel cases"); ax.legend(frameon=False, fontsize=9)
    ax = axes[1]
    rng = default_rng(99); Xn, yn, _ = gen_regime(N_TEST, "novel", rng)
    Xf, yf, _ = gen_regime(max(SIZES), "reference", rng)
    g = HistGradientBoostingClassifier(max_depth=3, max_iter=300, random_state=0).fit(Xf, yf)
    ax.hist(g.predict_proba(Xn)[:, 1], bins=25, color=NOV_C, alpha=0.85)
    ax.set_xlabel("Predicted mortality probability (novel cases)"); ax.set_ylabel("Count")
    ax.set_title("Confident point estimates under regime shift")
    fig.tight_layout(); fig.savefig(f"{figdir}/figure3_pseudo_precision.png", bbox_inches="tight"); plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.4))
    ax = axes[0]
    selm = sel.groupby(["regime", "coverage"])["brier_retained"].mean().reset_index()
    for regime, c in [("reference", REF_C), ("novel", NOV_C)]:
        s = selm[selm.regime == regime].sort_values("coverage")
        ax.plot(s.coverage, s.brier_retained, "-o", color=c, label=regime.capitalize())
    ax.invert_xaxis(); ax.set_xlabel("Coverage (retained, high-confidence first)")
    ax.set_ylabel("Brier on retained cases"); ax.set_title("Confidence-based abstention only partly reduces error")
    ax.legend(frameon=False, fontsize=9)
    ax = axes[1]
    ax.hist(d_ref, bins=40, alpha=0.6, color=REF_C, label="Reference", density=True)
    ax.hist(d_nov, bins=40, alpha=0.6, color=NOV_C, label="Novel", density=True)
    ax.set_xlabel("Mahalanobis distance from reference"); ax.set_ylabel("Density")
    ax.set_title(f"Weak novelty detection (AUROC={ood_auroc:.2f})"); ax.legend(frameon=False, fontsize=9)
    fig.tight_layout(); fig.savefig(f"{figdir}/figure4_abstention_and_novelty.png", bbox_inches="tight"); plt.close(fig)


# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    out = os.path.join(args.root, "outputs")
    figs = os.path.join(args.root, "figures")
    tabs = os.path.join(args.root, "tables")
    for d in (out, figs, tabs):
        os.makedirs(d, exist_ok=True)

    t0 = time.time()
    df = run_sweep(args.seeds)
    df.to_csv(f"{out}/results_raw.csv", index=False)

    agg = df.groupby(["model", "regime", "training_n"]).agg(["mean", "std"]).reset_index()
    agg.columns = ["_".join(c).strip("_") for c in agg.columns]
    agg.to_csv(f"{out}/summary_by_size.csv", index=False)

    sel, nov = selective_and_novelty(args.seeds)
    sel.to_csv(f"{out}/selective_prediction.csv", index=False)
    sel_summary = (
        sel.groupby(["regime", "coverage"])["brier_retained"]
        .agg(["mean", "std"])
        .reset_index()
        .rename(columns={"brier_retained": "brier_retained"})
    )
    sel_summary.to_csv(f"{out}/selective_prediction_summary.csv", index=False)
    nov.to_csv(f"{out}/novelty_detection.csv", index=False)
    ood_auroc = float(nov.novelty_auroc.mean())

    a = anchors(args.seeds)
    sens = sensitivity(args.seeds)
    sens.to_csv(f"{out}/sensitivity.csv", index=False)

    # Mahalanobis distances for the novelty-detection figure (single reference fit)
    Xf, yf, _ = gen_regime(8000, "reference", default_rng(21))
    cov = EmpiricalCovariance().fit(Xf)
    d_ref = cov.mahalanobis(gen_regime(N_TEST, "reference", default_rng(22))[0])
    d_nov = cov.mahalanobis(gen_regime(N_TEST, "novel", default_rng(23))[0])

    make_figures(df, sel, d_ref, d_nov, ood_auroc,
                 a["bayes_brier_reference"], a["bayes_brier_novel"], args.seeds, figs)

    # Table 2: performance at largest training size
    big = df[df.training_n == max(SIZES)]
    t2 = (big.pivot_table(index="model", columns="regime",
                          values=["brier", "ece", "calibration_slope", "auroc",
                                  "sharpness", "high_confidence_error"],
                          aggfunc=["mean", "std"]))
    t2.to_csv(f"{tabs}/table2_performance_largest_training_size.csv")
    t2_rows = []
    order = list(models().keys())
    for model in order:
        g = big[big.model == model]
        ref = g[g.regime == "reference"]
        nov_big = g[g.regime == "novel"]
        t2_rows.append(
            "| {model} | {br_ref:.3f} ({sd_ref:.3f}) | {br_nov:.3f} ({sd_nov:.3f}) | "
            "{ece_nov:.3f} ({ece_sd:.3f}) | {slope:.3f} ({slope_sd:.3f}) | "
            "{auroc:.3f} ({auroc_sd:.3f}) |".format(
                model=model,
                br_ref=ref.brier.mean(), sd_ref=ref.brier.std(),
                br_nov=nov_big.brier.mean(), sd_nov=nov_big.brier.std(),
                ece_nov=nov_big.ece.mean(), ece_sd=nov_big.ece.std(),
                slope=nov_big.calibration_slope.mean(),
                slope_sd=nov_big.calibration_slope.std(),
                auroc=nov_big.auroc.mean(), auroc_sd=nov_big.auroc.std(),
            )
        )
    with open(f"{tabs}/table2_performance_largest_training_size.md", "w") as f:
        f.write("| Model (n=8,000) | Brier reference | Brier novel | ECE novel | Calibration slope novel | AUROC novel |\n")
        f.write("|:--|:--|:--|:--|:--|:--|\n")
        f.write("\n".join(t2_rows) + "\n")

    # Table S3: sensitivity
    s3 = sens.groupby("scenario").agg(["mean", "std"]).round(3)
    s3.to_csv(f"{tabs}/table_s3_sensitivity_analysis.csv")
    s3_mean = sens.groupby("scenario").mean(numeric_only=True).round(3)
    with open(f"{tabs}/table_s3_sensitivity_analysis.md", "w") as f:
        f.write("| Scenario | Prevalence | Aleatoric floor | Model Brier | ECE | AUROC |\n")
        f.write("|:--|--:|--:|--:|--:|--:|\n")
        for scenario in ["main", "concept_shift_only_no_feature_shift", "prevalence_matched_novel"]:
            row = s3_mean.loc[scenario]
            f.write(
                f"| {scenario} | {row.outcome_prevalence:.3f} | {row.bayes_brier:.3f} | "
                f"{row.model_brier:.3f} | {row.ece:.3f} | {row.auroc:.3f} |\n"
            )

    manifest = dict(
        seeds=args.seeds, features=FEATURES,
        beta_ref=BETA_REF.tolist(), beta_novel=BETA_NOV.tolist(),
        mu_novel=MU_NOV.tolist(), intercept_ref=B0_REF, intercept_novel=B0_NOV,
        train_sizes=SIZES, test_size=N_TEST,
        novelty_detection_auroc=ood_auroc, **a,
        numpy=np.__version__, pandas=pd.__version__,
        python=sys.version.split()[0])
    with open(f"{out}/reproducibility_manifest.json", "w") as f:
        json.dump(manifest, f, indent=2)

    lines = ["# Reproducibility Run Summary", "",
             f"Seeds: {args.seeds}",
             f"Reference Bayes Brier: {a['bayes_brier_reference']:.3f}",
             f"Novel Bayes Brier: {a['bayes_brier_novel']:.3f}",
             f"Oracle (trained on novel) Brier on novel: {a['oracle_brier_novel']:.3f}",
             f"Mean novelty-detection AUROC: {ood_auroc:.3f}",
             f"Reference prevalence: {a['reference_prevalence']:.3f}",
             f"Novel prevalence: {a['novel_prevalence']:.3f}",
             f"Runtime: {time.time() - t0:.0f}s"]
    with open(f"{out}/run_summary.md", "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
